FONT_WIDTH = 5
FONT_HEIGHT = 7

# Precompute each glyph as a tuple of per-row bit patterns (5-bit ints,
# MSB = leftmost pixel) so drawing doesn't re-parse strings every frame.
FONT = {
    ch: tuple(
        int(row.replace("#", "1").replace(".", "0"), 2) for row in rows
    )
    for ch, rows in _GLYPHS_ASCII.items()
}


def glyph(ch: str):
    """Return the bit-row tuple for ch, falling back to space for unknown chars."""
    return FONT.get(ch.upper(), FONT[" "])
